// Builds src/features/openings/openingData.ts from scripts/data/openings.source.mjs.
// Checks: every line is legal, lines are unique, and Stockfish (depth 12) rates the final position
// as sane (|eval| <= 150 cp; gambits get 300 cp). Failing lines abort the build so bad data cannot ship.
import { writeFileSync, mkdirSync } from 'node:fs'
import { OPENINGS } from './data/openings.source.mjs'
import { Engine } from './lib/engine.mjs'
import { playSan, toFen } from './lib/minichess.mjs'

const DEPTH = Number(process.env.DEPTH ?? 12)
const GAMBIT = /gambit|attack|marshall|fried liver|traxler|latvian|englund|budapest|danish|blackmar|smith-morra|poisoned|staunton|schliemann|benko|albin|kalashnikov|sveshnikov|fianchetto/i
const engine = await new Engine({ hash: 64, threads: 1 }).init()

const seen = new Map()
const rows = []
const problems = []
const flagged = []
for (const [eco, name, san, idea] of OPENINGS) {
  let line
  try {
    line = playSan(san.split(' '))
  } catch (error) {
    problems.push(`${eco} ${name}: ${error.message}`)
    continue
  }
  const uci = line.uci.join(' ')
  if (seen.has(uci)) {
    problems.push(`${eco} ${name}: duplicate of "${seen.get(uci)}"`)
    continue
  }
  seen.set(uci, name)
  const fen = toFen(line.pos)
  const result = await engine.search(fen, DEPTH, 1)
  const top = result.lines[0]
  const turn = fen.split(' ')[1]
  let cp = top.mate !== null ? (top.mate > 0 ? 1000 : -1000) : top.cp
  if (turn === 'b') cp = -cp
  const limit = GAMBIT.test(name) ? 300 : 150
  if (Math.abs(cp) > limit) flagged.push(`${eco} ${name}: ${san} -> ${cp > 0 ? '+' : ''}${cp} cp (limit ${limit})`)
  rows.push({ eco, name, san, uci, idea, cp })
}
engine.quit()

if (problems.length || flagged.length) {
  console.error('PROBLEMS:\n' + problems.join('\n'))
  console.error('FLAGGED BY STOCKFISH:\n' + flagged.join('\n'))
  if (process.env.FORCE !== '1') process.exit(1)
}

rows.sort((a, b) => a.uci.localeCompare(b.uci))
const esc = (text) => JSON.stringify(text)
const body = rows
  .map((r) => `  { eco: ${esc(r.eco)}, name: ${esc(r.name)}, san: ${esc(r.san)}, uci: ${esc(r.uci)}${r.idea ? `, idea: ${esc(r.idea)}` : ''} },`)
  .join('\n')
const source = `// GENERATED by scripts/build-openings.mjs from scripts/data/openings.source.mjs — do not edit by hand.
// ${rows.length} lines. Each line was checked for legality and sanity-checked with Stockfish (depth ${DEPTH}).
export type OpeningEntry = {
  eco: string
  name: string
  /** Moves in SAN without move numbers, e.g. "e4 e5 Nf3". */
  san: string
  /** Same line in UCI, e.g. "e2e4 e7e5 g1f3". */
  uci: string
  /** Short idea of the opening, shown in the explorer (only for well-known families). */
  idea?: string
}

export const OPENING_BOOK: OpeningEntry[] = [
${body}
]
`
mkdirSync('src/features/openings', { recursive: true })
writeFileSync('src/features/openings/openingData.ts', source)
console.log(`Wrote ${rows.length} openings (${problems.length} problems, ${flagged.length} flagged).`)
